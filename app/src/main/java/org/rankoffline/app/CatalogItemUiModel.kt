package org.rankoffline.app

/** Media-neutral presentation model; Room entities and the legacy Anime model stay behind adapters. */
data class CatalogItemUiModel(
    val stableId: String,
    val mediaType: MediaType,
    val title: String,
    val genre: String? = null,
    val format: String? = null,
    val year: Int? = null,
    val startDate: String? = null,
    val filterCredit: String? = null,
    val popularity: Double? = null,
    val popularityRank: Int? = null,
    val finalScore: Double? = null,
    val qualityScore: Double? = null,
    val additiveScore: Double? = null,
    val categoryScore: Double? = null,
    val status: String? = null,
    val localCoverPath: String? = null,
    val coverResolutionState: CoverResolutionState = CoverResolutionState.UNKNOWN,
    val groupId: String? = null,
    val groupType: String? = null,
    val representativeItemId: String? = null,
    val sharedCoverMediaId: String? = null,
    val memberCount: Int = 0,
    val ratedCount: Int = 0,
    val derived: Boolean = false
)

fun MediaListEntry.toCatalogItemUiModel(): CatalogItemUiModel = when (this) {
    is MediaListEntry.Item -> CatalogItemUiModel(
        stableId = value.id,
        mediaType = value.mediaType,
        title = value.title,
        genre = value.genre,
        format = value.format,
        year = value.year,
        startDate = value.startDate,
        filterCredit = value.filterCredit,
        popularity = value.popularity,
        popularityRank = value.popularityRank,
        finalScore = value.finalScore,
        qualityScore = value.qualityScore,
        additiveScore = value.additiveScore,
        categoryScore = value.categoryScore,
        status = value.status,
        localCoverPath = value.localCoverPath,
        coverResolutionState = value.coverResolutionState,
        sharedCoverMediaId = value.sharedCoverMediaId
    )
    is MediaListEntry.Group -> CatalogItemUiModel(
        stableId = value.id,
        mediaType = value.mediaType,
        title = value.displayTitle,
        popularity = popularity,
        popularityRank = popularityRank,
        finalScore = finalScore,
        qualityScore = qualityScore,
        additiveScore = additiveScore,
        categoryScore = categoryScore,
        localCoverPath = value.localCoverPath,
        coverResolutionState = value.coverResolutionState,
        groupId = value.id,
        groupType = value.groupType,
        representativeItemId = representativeMediaId,
        sharedCoverMediaId = sharedCoverMediaId,
        memberCount = memberCount,
        ratedCount = ratedCount,
        derived = derived
    )
}

fun Anime.toCatalogItemUiModel(): CatalogItemUiModel = CatalogItemUiModel(
    stableId = id,
    mediaType = mediaType,
    title = title,
    genre = genre,
    format = format,
    year = metadataYear(),
    startDate = startDate,
    filterCredit = if (mediaType == MediaType.ANIME) studio else filterCredit,
    popularity = popularity?.toDouble(),
    popularityRank = popularityRank,
    finalScore = finalScore,
    qualityScore = baseScore,
    additiveScore = additiveScore,
    categoryScore = categoryScore,
    status = status,
    localCoverPath = localCoverPath,
    coverResolutionState = coverResolutionState,
    groupId = groupId,
    groupType = groupType,
    representativeItemId = rootAnimeId,
    sharedCoverMediaId = sharedCoverMediaId,
    memberCount = memberCount,
    ratedCount = ratedCount,
    derived = derived
)

/** Temporary boundary while stable Anime screens migrate to [CatalogItemUiModel]. */
fun CatalogItemUiModel.toLegacyAnimeDisplay(): Anime = Anime(
    id = stableId,
    title = title,
    mediaType = mediaType,
    popularity = popularity?.toInt(),
    popularityRank = popularityRank,
    finalScore = finalScore,
    baseScore = qualityScore,
    additiveScore = additiveScore,
    categoryScore = categoryScore,
    status = status,
    localCoverPath = localCoverPath,
    coverResolutionState = coverResolutionState,
    format = format,
    seasonYear = year,
    startDate = startDate,
    genre = genre,
    filterCredit = filterCredit,
    groupId = groupId,
    groupType = groupType,
    rootAnimeId = representativeItemId,
    sharedCoverMediaId = sharedCoverMediaId,
    memberCount = memberCount,
    ratedCount = ratedCount,
    derived = derived
)
