#!/usr/bin/env ruby
# frozen_string_literal: true

root = File.expand_path("..", __dir__)
ignored = %w[.git .gradle .idea __pycache__ build]
paths = Dir.glob("**/*", File::FNM_DOTMATCH, base: root).reject do |path|
  path.split("/").any? { |part| ignored.include?(part) } ||
    File.basename(path).end_with?(".pyc") ||
    %w[. ..].include?(File.basename(path))
end.sort

lines = paths.map do |path|
  depth = path.count("/")
  name = File.basename(path) + (File.directory?(File.join(root, path)) ? "/" : "")
  "#{"  " * depth}- #{name}"
end

content = <<~MARKDOWN
  # Project tree

  Generated by `scripts/update_project_tree.rb`. Build outputs, IDE state and
  other ignored local files are excluded.

  ```text
  RankOffline/
  #{lines.join("\n")}
  ```
MARKDOWN

File.write(File.join(root, "docs", "PROJECT_TREE.md"), content)
